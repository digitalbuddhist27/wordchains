/**
 * The link graph. Each entry is [from, to, tier]: FROM + TO makes a compound
 * word or a common two-word phrase. Chains are walked out of this at runtime,
 * so the number of possible chains is a property of the graph, not a fixed list.
 *
 * tier 1 = everyday, 2 = a step sideways, 3 = harder.
 * Every word is at least MIN_WORD_LENGTH letters, which rules out the short
 * connectors (OUT, WAY, TOP, KEY, AIR, SUN) that make blanks trivial.
 * `npm run check:chains` enforces the length rule, rejects self-links and
 * duplicate pairs, and fails the build if the graph cannot produce a chain at
 * every difficulty.
 *
 * Adding links: append pairs here. Ten new pairs on a well-connected hub word
 * multiply out to far more than ten new chains.
 */
